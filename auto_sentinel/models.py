"""Data models and schemas for auto-sentinel (The Data Contract).

Defines standard schemas shared across all 4 stages:
1. SecurityEvent (Stage 1: The Eyes)
2. Alert (Stage 2: The Brain)
3. RemediationAction & RemediationResult (Stage 3: The Hands)
4. AuditRecord (Stage 4: The Black Box)
"""

from datetime import datetime, timezone
from enum import Enum
from typing import Any, Dict, List, Optional
from uuid import uuid4
from pydantic import BaseModel, Field


class EventType(str, Enum):
    """Types of raw telemetry events collected by Stage 1."""
    AUTH_FAILURE = "AUTH_FAILURE"
    AUTH_SUCCESS = "AUTH_SUCCESS"
    PROCESS_SPAWNED = "PROCESS_SPAWNED"
    NETWORK_CONNECTION = "NETWORK_CONNECTION"
    FILE_MODIFIED = "FILE_MODIFIED"


class Severity(str, Enum):
    """Incident severity classification."""
    LOW = "LOW"
    MEDIUM = "MEDIUM"
    HIGH = "HIGH"
    CRITICAL = "CRITICAL"


class MitreTactic(str, Enum):
    """MITRE ATT&CK Tactic references."""
    INITIAL_ACCESS = "TA0001"
    EXECUTION = "TA0002"
    PERSISTENCE = "TA0003"
    PRIVILEGE_ESCALATION = "TA0004"
    DEFENSE_EVASION = "TA0005"
    CREDENTIAL_ACCESS = "TA0006"


class SecurityEvent(BaseModel):
    """Raw telemetry event normalized from system logs or process tables (Stage 1 output)."""
    event_id: str = Field(default_factory=lambda: str(uuid4()))
    timestamp: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    event_type: EventType
    source: str = Field(..., description="Source of the event, e.g. 'auth.log', 'process_monitor'")
    source_ip: Optional[str] = Field(default=None, description="IP address associated with the event")
    user: Optional[str] = Field(default=None, description="Username associated with the event")
    process_name: Optional[str] = Field(default=None, description="Binary or command name")
    process_pid: Optional[int] = Field(default=None, description="OS Process ID")
    raw_message: str = Field(default="", description="Original raw log line or telemetry string")
    metadata: Dict[str, Any] = Field(default_factory=dict, description="Arbitrary contextual attributes")


class Alert(BaseModel):
    """Correlated security alert generated by the Detection Engine (Stage 2 output)."""
    alert_id: str = Field(default_factory=lambda: str(uuid4()))
    timestamp: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    rule_name: str
    severity: Severity
    mitre_tactic: MitreTactic
    mitre_technique_id: str = Field(..., description="MITRE Technique, e.g. 'T1110' (Brute Force)")
    description: str
    target_ip: Optional[str] = None
    target_pid: Optional[int] = None
    target_process_name: Optional[str] = None
    triggering_events: List[SecurityEvent] = Field(default_factory=list)


class ActionType(str, Enum):
    """Available remediation actions."""
    BLOCK_IP = "BLOCK_IP"
    KILL_PROCESS = "KILL_PROCESS"
    ISOLATE_HOST = "ISOLATE_HOST"


class RemediationResult(BaseModel):
    """Outcome receipt of an active response action (Stage 3 output)."""
    action_id: str = Field(default_factory=lambda: str(uuid4()))
    timestamp: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    action_type: ActionType
    target: str = Field(..., description="Target value, e.g. IP '1.2.3.4' or PID '4091'")
    success: bool
    details: str
    stdout: str = ""
    stderr: str = ""


class AuditRecord(BaseModel):
    """Cryptographically linked audit ledger entry (Stage 4 output)."""
    record_id: int
    timestamp: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    event_type: str
    payload: Dict[str, Any]
    prev_hash: str = Field(..., description="SHA-256 of the preceding record for blockchain-like integrity")
    current_hash: str = Field(..., description="SHA-256 of this record's canonical representation")
